CREATE TABLE unit_codes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code SMALLINT NOT NULL UNIQUE CHECK (code BETWEEN 1 AND 99),
    description_fa VARCHAR(255) NOT NULL,
    description_en VARCHAR(255) NOT NULL,
    subject_1 TEXT,
    subject_2 TEXT,
    subject_3 TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE physical_codes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code SMALLINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100 MAXVALUE 9999),
    description_fa VARCHAR(255) NOT NULL,
    description_en VARCHAR(255) NOT NULL,
    weight_kg NUMERIC(12,3) CHECK (weight_kg IS NULL OR weight_kg >= 0),
    length_cm NUMERIC(12,2) CHECK (length_cm IS NULL OR length_cm >= 0),
    width_cm NUMERIC(12,2) CHECK (width_cm IS NULL OR width_cm >= 0),
    height_cm NUMERIC(12,2) CHECK (height_cm IS NULL OR height_cm >= 0),
    subject_1 TEXT,
    subject_2 TEXT,
    subject_3 TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_physical_codes_code UNIQUE (code),
    CONSTRAINT ck_physical_codes_code CHECK (code BETWEEN 1 AND 9999)
);

CREATE TABLE products (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    description_fa TEXT NOT NULL,
    description_en TEXT NOT NULL,
    real_part_number VARCHAR(100) NOT NULL,
    product_code VARCHAR(13) NOT NULL UNIQUE CHECK (product_code ~ '^[0-9]{13}$'),
    product_group_code_id UUID NOT NULL REFERENCES product_group_codes(id),
    unit_code_id UUID NOT NULL REFERENCES unit_codes(id),
    physical_code_id UUID REFERENCES physical_codes(id),
    code_1 VARCHAR(20) CHECK (code_1 IS NULL OR code_1 ~ '^[0-9]{20}$'),
    code_2 VARCHAR(20) CHECK (code_2 IS NULL OR code_2 ~ '^[0-9]{20}$'),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'INACTIVE', 'DISCONTINUED')),
    subject_1 TEXT,
    subject_2 TEXT,
    subject_3 TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);

CREATE TABLE product_code_details (
    product_id UUID PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
    vehicle_type_code_id UUID NOT NULL REFERENCES vehicle_type_codes(id),
    vehicle_brand_code_id UUID NOT NULL REFERENCES vehicle_brand_codes(id),
    part_brand_code_id UUID NOT NULL REFERENCES part_brand_codes(id),
    packaging_code_id UUID NOT NULL REFERENCES packaging_codes(id),
    quality_code_id UUID NOT NULL REFERENCES quality_codes(id),
    product_serial SMALLINT NOT NULL CHECK (product_serial BETWEEN 1 AND 9999),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_product_code_source_serial UNIQUE (vehicle_type_code_id, vehicle_brand_code_id, part_brand_code_id, packaging_code_id, quality_code_id, product_serial)
);

CREATE TABLE product_serial_counters (
    vehicle_type_code_id UUID NOT NULL REFERENCES vehicle_type_codes(id),
    vehicle_brand_code_id UUID NOT NULL REFERENCES vehicle_brand_codes(id),
    part_brand_code_id UUID NOT NULL REFERENCES part_brand_codes(id),
    packaging_code_id UUID NOT NULL REFERENCES packaging_codes(id),
    quality_code_id UUID NOT NULL REFERENCES quality_codes(id),
    last_serial SMALLINT NOT NULL CHECK (last_serial BETWEEN 1 AND 9999),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (vehicle_type_code_id, vehicle_brand_code_id, part_brand_code_id, packaging_code_id, quality_code_id)
);

CREATE TABLE product_images (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    image_url TEXT NOT NULL CHECK (char_length(image_url) <= 2000),
    alt_text VARCHAR(255),
    sort_order SMALLINT NOT NULL CHECK (sort_order BETWEEN 1 AND 10),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_product_image_order UNIQUE (product_id, sort_order)
);

CREATE INDEX idx_products_real_part_number ON products (real_part_number);
CREATE INDEX idx_products_status ON products (status) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_group ON products (product_group_code_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_code ON products (product_code) WHERE deleted_at IS NULL;
CREATE INDEX idx_product_images_product ON product_images (product_id);

CREATE OR REPLACE FUNCTION enforce_product_image_limit()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' AND (
        SELECT COUNT(*) FROM product_images WHERE product_id = NEW.product_id
    ) >= 10 THEN
        RAISE EXCEPTION 'A product can have at most 10 images';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_product_image_limit
BEFORE INSERT ON product_images
FOR EACH ROW EXECUTE FUNCTION enforce_product_image_limit();

