    local_cost NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (local_cost >= 0),
    other_cost NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (other_cost >= 0),
    markup_amount NUMERIC(18,4) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
