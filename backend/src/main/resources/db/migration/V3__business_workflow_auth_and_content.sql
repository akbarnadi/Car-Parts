CREATE TABLE user_roles (
    user_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    role_id SMALLINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE auth_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_auth_sessions_user ON auth_sessions(user_id);
CREATE INDEX idx_auth_sessions_expiry ON auth_sessions(expires_at);

CREATE TABLE customers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID UNIQUE REFERENCES app_users(id) ON DELETE SET NULL,
    full_name VARCHAR(160) NOT NULL,
    phone VARCHAR(60),
    email VARCHAR(320),
    company VARCHAR(160),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_customers_phone ON customers(phone);
CREATE INDEX idx_customers_email ON customers(LOWER(email));

CREATE TABLE suppliers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(200) NOT NULL,
    country VARCHAR(100),
    contact_name VARCHAR(160),
    email VARCHAR(320),
    phone VARCHAR(80),
    currencies VARCHAR(120),
    rating SMALLINT CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE customer_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    request_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    source VARCHAR(20) NOT NULL CHECK (source IN ('SITE','PHONE','WHATSAPP','EMAIL','INSTAGRAM','OTHER')),
    customer_id UUID REFERENCES customers(id) ON DELETE SET NULL,
    contact_name VARCHAR(160),
    contact_phone VARCHAR(80),
    contact_email VARCHAR(320),
    requested_part_number VARCHAR(120),
    request_text TEXT NOT NULL,
    vehicle_text VARCHAR(500),
    status VARCHAR(24) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','QUALIFYING','IN_PROGRESS','QUOTED','WON','LOST','CLOSED')),
    assigned_to UUID REFERENCES app_users(id) ON DELETE SET NULL,
    created_by_user_id UUID REFERENCES app_users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_customer_requests_status ON customer_requests(status, created_at DESC);

CREATE TABLE workflow_cases (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    case_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    request_id UUID NOT NULL UNIQUE REFERENCES customer_requests(id) ON DELETE RESTRICT,
    product_id UUID REFERENCES products(id) ON DELETE SET NULL,
    manager_user_id UUID REFERENCES app_users(id) ON DELETE SET NULL,
    stage VARCHAR(40) NOT NULL DEFAULT 'REQUESTED' CHECK (stage IN ('REQUESTED','PRODUCT_CREATED','SOURCING','SUPPLIER_QUOTED','INTERNAL_COSTED','CUSTOMER_QUOTED','CUSTOMER_AGREED','SUPPLIER_ORDERED','IN_TRANSIT','CUSTOMS','LOCAL_WAREHOUSE','READY_FOR_DELIVERY','DELIVERED','CLOSED','CANCELLED')),
    priority VARCHAR(12) NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('LOW','NORMAL','HIGH','URGENT')),
    agreement_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (agreement_status IN ('PENDING','ACCEPTED','REJECTED','EXPIRED')),
    next_action_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_workflow_cases_stage ON workflow_cases(stage, updated_at DESC);
CREATE INDEX idx_workflow_cases_manager ON workflow_cases(manager_user_id, updated_at DESC);

CREATE TABLE supplier_quotes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    case_id UUID NOT NULL REFERENCES workflow_cases(id) ON DELETE CASCADE,
    supplier_id UUID REFERENCES suppliers(id) ON DELETE SET NULL,
    supplier_name_snapshot VARCHAR(200) NOT NULL,
    country VARCHAR(100),
    currency VARCHAR(3) NOT NULL,
    unit_price NUMERIC(18,4) NOT NULL CHECK (unit_price >= 0),
    quantity NUMERIC(12,3) NOT NULL DEFAULT 1 CHECK (quantity > 0),
    foreign_transport NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (foreign_transport >= 0),
    international_shipping NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (international_shipping >= 0),
    available_quantity NUMERIC(12,3),
    lead_days INTEGER CHECK (lead_days IS NULL OR lead_days >= 0),
    valid_until DATE,
    status VARCHAR(16) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED','SELECTED','REJECTED','EXPIRED')),
    quoted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id UUID REFERENCES app_users(id) ON DELETE SET NULL
);
CREATE INDEX idx_supplier_quotes_case ON supplier_quotes(case_id, quoted_at DESC);

CREATE TABLE customer_quotes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    quote_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    case_id UUID NOT NULL REFERENCES workflow_cases(id) ON DELETE CASCADE,
    currency VARCHAR(3) NOT NULL,
    supplier_cost NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (supplier_cost >= 0),
    logistics_cost NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (logistics_cost >= 0),
