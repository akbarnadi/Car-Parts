CREATE INDEX idx_customer_quotes_case ON customer_quotes(case_id, created_at DESC);

CREATE TABLE sales_orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    case_id UUID UNIQUE REFERENCES workflow_cases(id) ON DELETE SET NULL,
    customer_id UUID REFERENCES customers(id) ON DELETE SET NULL,
    currency VARCHAR(3) NOT NULL,
    total_amount NUMERIC(18,4) NOT NULL CHECK (total_amount >= 0),
    paid_amount NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_PAYMENT' CHECK (status IN ('PENDING_PAYMENT','CONFIRMED','PROCUREMENT','IN_TRANSIT','CUSTOMS','READY','DELIVERED','CANCELLED')),
    customer_note TEXT,
    internal_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE order_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id UUID NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
    product_id UUID REFERENCES products(id) ON DELETE SET NULL,
    part_number_snapshot VARCHAR(120),
    description_snapshot VARCHAR(500) NOT NULL,
    quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(18,4) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE payments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id UUID NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
    amount NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL,
    method VARCHAR(40),
    reference VARCHAR(160),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','CONFIRMED','FAILED','REFUNDED')),
    received_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id UUID REFERENCES app_users(id) ON DELETE SET NULL
);
CREATE INDEX idx_payments_order ON payments(order_id, created_at DESC);

CREATE TABLE shipments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    case_id UUID REFERENCES workflow_cases(id) ON DELETE SET NULL,
    order_id UUID REFERENCES sales_orders(id) ON DELETE SET NULL,
    tracking_number VARCHAR(160),
    carrier VARCHAR(160),
    origin_country VARCHAR(100),
    destination_country VARCHAR(100),
